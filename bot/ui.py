"""Общий каркас экранов: одна разметка на весь бот.

Уведомления в `tasks/manager.py` рисовались карточкой — заголовок, линейка,
факты, линейка, подвал, — и читались с телефона за секунду. Экраны меню
собирались вручную: сто двадцать семь мест с `"\n".join(...)`, и у каждого
свой отступ после заголовка, свой подвал, свой предел обрезки. Разнобой
виден не по отдельному экрану, а по переходу между ними: глаз каждый раз
заново ищет, где кончается шапка.

Поэтому каркас здесь один и на всех. Тексты он не меняет — меняет только
то, что вокруг них.

Правило простое: **заголовок отвечает, где я, линейка отделяет его от дела,
подвал — то, что можно не читать.** Всё, что не укладывается в это, лучше
писать вручную, чем растягивать каркас под исключение.
"""
from __future__ import annotations

import html

# Линейка. Четырнадцать символов — столько влезает в узкую строку телефона,
# не переносясь; шире она начинает выглядеть как ошибка вёрстки.
RULE = "━━━━━━━━━━━━━━"

# Разделитель в шапке: «🎁 Гифт-карты · Мой магазин». В боте их было два —
# `·` в шестнадцати местах и `•` в двух, — и второй бросался в глаза именно
# редкостью.
SEP = "·"

# Предел на сообщение. У Telegram он 4096; берём с запасом на подпись и
# закрывающие теги. Пределов было три — 3500, 3900 и 4000, — то есть
# правила не было, было три случая.
LIMIT = 3900


def esc(text) -> str:
    """Чужой текст перед вставкой в HTML-сообщение.

    Название магазина, товара, письмо покупателя — одиночный `<` в любом из
    них роняет отправку целиком, и продавец не получает ничего.
    """
    return html.escape(str(text if text is not None else ""))


def clip(text: str, limit: int = LIMIT) -> str:
    """Обрезка по границе слова, а не по счёту символов.

    Обрыв посреди слова («…"subcategor») продавец пересылает в поддержку как
    есть, и там получают огрызок.
    """
    text = str(text or "")
    if len(text) <= limit:
        return text
    cut = text[:limit]
    space = max(cut.rfind(" "), cut.rfind("\n"))
    return (cut[:space] if space > limit * 0.6 else cut).rstrip() + "…"


def head(title: str, subtitle: str = "") -> str:
    """Шапка: где я и в каком магазине. Подзаголовок экранируется, заголовок
    нет — он наш собственный и может нести разметку."""
    tail = f" {SEP} {esc(subtitle)}" if subtitle else ""
    return f"{title}{tail}"


def screen(title: str, body, subtitle: str = "", footer: str = "",
           limit: int = LIMIT) -> str:
    """Экран меню: шапка, линейка, тело, и подвал под второй линейкой.

    `body` — список строк; `None` в нём отбрасывается, пустая строка
    остаётся, потому что это намеренный отступ между блоками. Фильтр по
    правдивости однажды уже съел все разделяющие пустые строки разом.
    """
    parts = [head(title, subtitle), RULE]
    parts += [b for b in (body or []) if b is not None]
    if footer:
        parts += ["", RULE, footer]
    return clip("\n".join(parts), limit)


def card(title: str, body, footer: str = "") -> str:
    """Карточка уведомления: то же самое, но без подзаголовка и без обрезки.

    Уведомление приходит само и читается на бегу, поэтому подвал отбит
    линейкой всегда, а не только когда он есть.
    """
    parts = [title, RULE, *[b for b in (body or []) if b is not None]]
    if footer:
        parts += [RULE, footer]
    return "\n".join(parts)
