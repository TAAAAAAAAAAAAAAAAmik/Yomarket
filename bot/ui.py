# Ярлык шире этого в половину строки не влезает и переносится на второй ряд.
# Ряд Telegram делит на равные половины, поэтому решает не сумма надписей, а
# длинная из двух. Восемнадцать — по замеру живых надписей бота: на них
# приходится провал в распределении, «🌐 Войти в панель» (17) и «➕ Добавить
# товар» (17) в половину строки помещаются, «💸 Вывести средства» (19) уже
# нет. Промах в эту сторону стоит перенесённой на вторую строку надписи —
# ряд от этого выше, но всё равно ниже, чем два отдельных ряда.
WIDE = 18

# Что на экране занимает две колонки, а не одну. Считать `len` нельзя:
# «↩️ Возвраты» — это одиннадцать кодовых точек, из которых два невидимых
# селектора, а рисуется оно как девять знаков, где стрелка вдвое шире буквы.
_ZERO = "️‍⃣"
_WIDE_RANGES = (
    (0x2190, 0x21FF),    # стрелки: ⬅️ ↩️ ▶️
    (0x2300, 0x23FF),    # ⏳ ⏭ ⌛
    (0x25A0, 0x27BF),    # ▪️ ☑️ ✅ ❌ ➕
    (0x2B00, 0x2BFF),    # ⬛ ⭐
    (0x1F000, 0x1FAFF),  # собственно эмодзи
)


def width(text: str) -> int:
    """Ширина ярлыка в знакоместах — приблизительно, и намеренно.

    Точной её не знает никто: у Telegram шрифт пропорциональный, и одна и та
    же надпись на разных телефонах занимает разное место. Нам хватает
    ответа на единственный вопрос — «влезут ли две такие в строку», — и
    ошибка здесь стоит перенесённой строчки, а не потерянных денег.
    """
    total = 0
    for ch in str(text or ""):
        if ch in _ZERO:
            continue
        code = ord(ch)
        total += 2 if any(lo <= code <= hi for lo, hi in _WIDE_RANGES) else 1
    return total


def sizes(labels, wide: int = WIDE, alone=()) -> list[int]:
    """Разложить ярлыки: короткие — по две в ряд, длинные — по одной.

    Отдаёт список размеров рядов для `builder.adjust(*sizes)`. Отдельной
    функцией, а не сразу раскладкой, — чтобы её можно было проверить тестом
    на голом списке надписей, без сборки клавиатуры.

    `alone` — номера позиций, которым нельзя стоять в паре ни с чем. Это про
    кнопки, которые делают что-то безвозвратное: «🧹 Очистить всё» рядом с
    «⬅️ Назад» — обе короткие, обе под большим пальцем, и промах стирает
    список без вопроса. Признак задаётся списком позиций, а не разбором
    надписи: сегодня она «Очистить всё», завтра «Сбросить», и проверка по
    словам молча перестанет срабатывать.
    """
    alone = set(alone)
    out: list[int] = []
    i = 0
    labels = list(labels)
    while i < len(labels):
        pair = (i + 1 < len(labels)
                and i not in alone and i + 1 not in alone
                and width(labels[i]) <= wide
                and width(labels[i + 1]) <= wide)
        out.append(2 if pair else 1)
        i += 2 if pair else 1
    return out or [1]


def lay(builder, wide: int = WIDE, solo=()):
    """Разложить уже набранные кнопки по ширине их надписей.

    Обычный `adjust(1)` ставит в столбик и длинный «🎮 Xbox Game Pass Ultimate
    1 месяц», и короткое «⬅️ Назад», — и экран из восьми кнопок уезжает за
    край телефона, хотя половина из них занимает треть строки. Раскладка по
    ширине оставляет длинным целую строку, а короткие сдваивает.

    Вызывается **после** того, как добавлены все кнопки: `adjust` переставляет
    всю клавиатуру целиком, а не только новые ряды. По той же причине это
    не годится для экранов подтверждения — там «✅ Да» и «❌ Отмена» коротки
    оба, встанут рядом, и промах пальцем будет стоить чужих денег. Там
    остаётся столбик.

    `solo` — набор `callback_data` кнопок, которым нельзя стоять в паре:
    безвозвратное действие не должно оказаться под соседним пальцем с
    «Назад». Сравнение по `callback_data`, а не по надписи: надпись — текст
    для человека, её меняют, и проверка по ней тихо перестала бы работать.
    """
    solo = set(solo)
    labels, alone = [], []
    for i, b in enumerate(builder.buttons):
        labels.append(b.text)
        if getattr(b, "callback_data", None) in solo:
            alone.append(i)
    builder.adjust(*sizes(labels, wide, alone))
    return builder
