"""Общий каркас экранов: одна разметка на весь бот.

Уведомления в `tasks/manager.py` рисовались карточкой — заголовок, линейка,
факты, линейка, подвал, — и читались с телефона за секунду. Экраны меню
собирались вручную: сто двадцать семь мест с `"\n".join(...)`, и у каждого
свой отступ после заголовка, свой подвал, свой предел обрезки. Разнобой
виден не по отдельному экрану, а по переходу между ними: глаз каждый раз
заново ищет, где кончается шапка.

Поэтому каркас здесь один и на всех. Тексты он не меняет — меняет только
то, что вокруг них.

Правило простое: **заголовок отвечает, где я, линейка отделяет его от дела,
подвал — то, что можно не читать.** Всё, что не укладывается в это, лучше
писать вручную, чем растягивать каркас под исключение.
"""
from __future__ import annotations

import html
import re

# Линейка. Четырнадцать символов — столько влезает в узкую строку телефона,
# не переносясь; шире она начинает выглядеть как ошибка вёрстки.
RULE = "━━━━━━━━━━━━━━"

# Разделитель в шапке: «🎁 Гифт-карты · Мой магазин». В боте их было два —
# `·` в шестнадцати местах и `•` в двух, — и второй бросался в глаза именно
# редкостью.
SEP = "·"

# Предел на сообщение. У Telegram он 4096; берём с запасом на подпись и
# закрывающие теги. Пределов было три — 3500, 3900 и 4000, — то есть
# правила не было, было три случая.
LIMIT = 3900


def esc(text) -> str:
    """Чужой текст перед вставкой в HTML-сообщение.

    Название магазина, товара, письмо покупателя — одиночный `<` в любом из
    них роняет отправку целиком, и продавец не получает ничего.
    """
    return html.escape(str(text if text is not None else ""))


def admin_hint(user_id, *lines) -> str:
    """Кусок экрана, который видит только админ. Остальным — пустая строка.

    Служебный совет («чем смотреть дальше — /cat_debug») продавцу не
    годится: команда ему скрыта, он наберёт её и получит ровно то же, что
    на несуществующую. Но владельцу тот же экран обязан подсказывать, куда
    идти, — значит текст не удаляется, а прячется.

    Место одно на всё, и это не вкусовщина: проверка «не советует ли экран
    скрытую команду» разбирает исходники, и отличить строку для владельца
    от строки для продавца она может только по тому, внутри чего строка
    лежит.

    Пустая строка среди `lines` — намеренный отступ, и он сохраняется:
    фильтр по правдивости однажды уже съел все разделители разом.
    """
    from storage import is_admin
    if not user_id or not is_admin(int(user_id)):
        return ""
    return "\n".join(str(x) for x in lines if x is not None)


def build_mark(user_id) -> str:
    """Код сборки — админам, и никому больше. Остальным пустая строка.

    Метка ставилась на экранах отказов затем, чтобы по снимку было видно,
    доехал ли до контейнера код: «кнопка не работает» и «в контейнере
    старая сборка» выглядят одинаково. Читает её при этом ВЛАДЕЛЕЦ, а
    висела она у продавца, которому не говорит ничего и рассказывает о боте
    то, чего он не спрашивал.

    Прячется она по тому же правилу, что и `/version`: служебное показывает
    устройство самого бота, а продавец купил подписку на сервис. Владельцу
    метка остаётся — он воспроизводит беду у себя и видит её на том же
    месте.

    Пустая строка, а не «—»: место, где метки нет, у продавца просто не
    занято.
    """
    from handlers.start import BOT_VERSION
    return admin_hint(user_id, f"  <code>{esc(BOT_VERSION)}</code>")


# Что имеет смысл копировать нажатием: номер карты, телефон, счёт, адрес
# кошелька. Обёрнутое в `<code>` Telegram и рисует моноширинным, и копирует
# по нажатию целиком — значит в тег должно попасть РОВНО то, что вставляют
# в поле перевода, и ни слова больше.
# Плюс — часть номера, а не украшение перед ним: скопированный «7 900…»
# без него в поле перевода не годится.
_DIGITS = re.compile(r"(?<![\w/])\+?[\d][\d \-]{4,}[\d](?![\w/])")
_TOKEN = re.compile(r"(?<![\w/])[A-Za-z0-9]{20,}(?![\w/])")


def copyable(text) -> str:
    """Реквизиты для экрана: номера — моноширинно и с копированием.

    Обернуть в `<code>` ВЕСЬ текст было бы проще, но тогда нажатие
    скопировало бы вместе с картой и «в комментарии — свой ник», а это
    уходит в поле перевода и остаётся там.

    Что не опознали — остаётся обычным текстом: неудачное распознавание
    стоит одного лишнего копирования руками, а лишний `<code>` вокруг
    целой фразы — испорченного перевода.
    """
    out = esc(text)
    # От откусывания адреса кошелька, начинающегося с цифр, защищает не
    # порядок правил, а `(?![\w/])` в цифровом: за цифрами не должно идти
    # буквы. Порядок здесь ни на что не влияет — проверено.
    for rule in (_TOKEN, _DIGITS):
        out = rule.sub(lambda m: f"<code>{m.group(0)}</code>", out)
    return out


def clip(text: str, limit: int = LIMIT) -> str:
    """Обрезка по границе слова, а не по счёту символов.

    Обрыв посреди слова («…"subcategor») продавец пересылает в поддержку как
    есть, и там получают огрызок.
    """
    text = str(text or "")
    if len(text) <= limit:
        return text
    cut = text[:limit]
    space = max(cut.rfind(" "), cut.rfind("\n"))
    return (cut[:space] if space > limit * 0.6 else cut).rstrip() + "…"


def head(title: str, subtitle: str = "") -> str:
    """Шапка: где я и в каком магазине. Подзаголовок экранируется, заголовок
    нет — он наш собственный и может нести разметку."""
    tail = f" {SEP} {esc(subtitle)}" if subtitle else ""
    return f"{title}{tail}"


def screen(title: str, body, subtitle: str = "", footer: str = "",
           limit: int = LIMIT) -> str:
    """Экран меню: шапка, линейка, тело, и подвал под второй линейкой.

    `body` — список строк; `None` в нём отбрасывается, пустая строка
    остаётся, потому что это намеренный отступ между блоками. Фильтр по
    правдивости однажды уже съел все разделяющие пустые строки разом.
    """
    parts = [head(title, subtitle), RULE]
    parts += [b for b in (body or []) if b is not None]
    if footer:
        parts += ["", RULE, footer]
    return clip("\n".join(parts), limit)


def card(title: str, body, footer: str = "") -> str:
    """Карточка уведомления: то же самое, но без подзаголовка и без обрезки.

    Уведомление приходит само и читается на бегу, поэтому подвал отбит
    линейкой всегда, а не только когда он есть.
    """
    parts = [title, RULE, *[b for b in (body or []) if b is not None]]
    if footer:
        parts += [RULE, footer]
    return "\n".join(parts)


