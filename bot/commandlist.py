"""Что видит клиент в списке команд, а что — только владелец.

`/version` печатал PostgreSQL, Redis, PID процесса, путь к каталогу данных
и имена переменных окружения. Продавцу это не нужно, а знать, из чего бот
собран и где живёт, ему тем более незачем: он купил подписку на сервис, а
не экскурсию по серверу. Диагностика при этом никуда не девается — она
нужна владельцу, — просто перестаёт быть общедоступной.

Списка два, и они делают разное:

* `MENU` — то, что Telegram показывает в кнопке «☰ Меню». Он короткий
  намеренно: список из полусотни строк не меню, а свалка.
* `EXTRA_PUBLIC` — команды, которые продавцу выполнять можно, но в меню им
  не место: они есть кнопками, а командой ими пользуется тот, кто и так
  знает имя.

Всё остальное — служебное, и оно скрыто. «Скрыто» здесь значит именно
скрыто: чужой команде бот отвечает ровно то же, что и несуществующей.
Ответ «эта команда не для тебя» рассказывал бы о существовании скрытой
части — то есть делал бы ровно то, чего мы избегаем.

Список закрытый и проверяется тестом: каждая зарегистрированная в боте
команда обязана быть либо здесь, либо скрытой ОСОЗНАННО. Новая
диагностика, добавленная через полгода, иначе оказалась бы публичной
молча — а заметил бы это продавец, а не мы.
"""
from __future__ import annotations

# Кнопка «☰ Меню» у продавца.
MENU: tuple[tuple[str, str], ...] = (
    ("menu", "Главное меню"),
    ("orders", "Заказы"),
    ("chats", "Чаты"),
    ("ads", "Объявления"),
    ("balance", "Баланс"),
    ("stats", "Статистика"),
    ("prices", "Цены и расписание"),
    ("stars", "Telegram Stars"),
    ("keyboard", "Показать или убрать кнопки"),
    ("help", "Поддержка"),
    ("policy", "Документы и условия"),
)

# Выполнять можно, в меню не показываем.
EXTRA_PUBLIC: frozenset[str] = frozenset({
    "start",                       # его Telegram показывает и сам
    "proxy",                       # свои прокси, есть кнопкой
    "pubg",                        # честный ответ «такого плагина нет»
    "watch_chat", "unwatch_chat",  # чат без заказа
    "logout",                      # отключить магазин
    "forget_me",                   # удаление данных обещано в политике
    # Свои поставщики и свой Fragment. Граница здесь проходит не по слову
    # «debug», а по тому, ЧЬЁ устройство команда показывает: кабинет
    # поставщика и сессия Fragment принадлежат продавцу, он их и чинит —
    # про то, из чего собран сам бот, они не говорят ничего.
    "apr_login", "apr_forget", "ns_login", "ns_forget",
    "apr_stock", "apr_balance", "apr_item", "apr_whoami", "apr_debug",
    "ns_stock", "ns_balance",
    "fragment_cookies", "fragment_debug", "fragment_js", "stars_probe",
})

PUBLIC: frozenset[str] = frozenset(name for name, _d in MENU) | EXTRA_PUBLIC


def name_of(text: str) -> str:
    """Имя команды из сообщения: `/orders@YoMarketBot 12` → `orders`.

    `@имя_бота` отрезается — в группе Telegram шлёт команду именно так, и
    сверка со словом целиком иначе не нашла бы ни одной.
    """
    head = str(text or "").strip().split(maxsplit=1)
    if not head or not head[0].startswith("/"):
        return ""
    return head[0][1:].split("@")[0]


def is_public(text: str) -> bool:
    """Можно ли эту команду выполнять продавцу без прав администратора."""
    return name_of(text) in PUBLIC
