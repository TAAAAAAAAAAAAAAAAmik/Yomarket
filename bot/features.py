"""Что из плагинов сейчас показывается продавцу, а что ещё нет.

Плагин, который «пока не показываем», прячется целиком или не прячется
вовсе. Убрать кнопку и оставить команду — это кнопка, о которой знает
только тот, кто её уже видел; убрать и то и другое, но оставить фоновую
выдачу — хуже всего: она тратит чужие TON, а выключить её продавцу нечем,
экрана-то нет.

Владельцу плагин остаётся: он его и доводит. Правило то же, что у кода
сборки и служебных команд — прячется не имя, а всё, что за ним.

Один переключатель на весь бот. Разложенный по местам («тут не покажем,
там не пустим»), он однажды не сойдётся сам с собой, и разойтись это может
молча.
"""
from __future__ import annotations

# Автовыдача звёзд Telegram через Fragment. Скрыта временно: покупка на
# Fragment доведена не до конца, и показывать продавцу то, что может не
# сработать с его деньгами, нельзя.
STARS_HIDDEN = True


def ad_templates_shown(user_id) -> bool:
    """Видит ли этот человек копию товара по образцу.

    Только админам — решение владельца. В отличие от звёзд, это не «пока
    не доделано», а свойство самой возможности: она создаёт товар на
    витрине по одному нажатию, без единого вопроса.

    Своя функция, а не тот же `stars_shown`: причины разные, и однажды они
    разойдутся — звёзды откроются всем, а копия останется закрытой.
    """
    from storage import is_admin
    return bool(user_id and is_admin(int(user_id)))


def stars_shown(user_id) -> bool:
    """Видит ли этот человек автовыдачу звёзд — и работает ли она у него."""
    if not STARS_HIDDEN:
        return True
    from storage import is_admin
    return bool(user_id and is_admin(int(user_id)))
